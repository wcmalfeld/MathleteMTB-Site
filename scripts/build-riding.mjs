#!/usr/bin/env node
// Builds the riding curriculum pages from content/riding/.
//   node scripts/build-riding.mjs
// Writes
//   riding/index.html          (curriculum map: pathways, coverage, sources)
//   riding/<slug>/index.html   (one per lesson)
// These are DRAFTS for coach review: every page is noindex, carries a draft
// banner and isn't linked from the rest of the site. check-site.mjs fails
// if these pages are out of date or any of that changes.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { SOURCES, ACCESS_LABELS, CHECKED_LABELS } from '../content/riding/sources.mjs';
import { PATHWAYS, RISK_CLASSES, LESSONS } from '../content/riding/curriculum.mjs';

const root = new URL('..', import.meta.url).pathname;
const SITE = 'https://www.mathletemtb.com/';
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export const STATUS = {
  draft: 'Draft: ready for editorial review',
  specialist: 'Draft: needs specialist authoring',
  outline: 'Outline: needs authoring',
  approved: 'Approved'
};

const bySlug = Object.fromEntries(LESSONS.map(l => [l.slug, l]));
const allSources = l => [...l.sources.primary, ...l.sources.comparison];
export const textVerified = l => allSources(l).some(id => SOURCES[id] && SOURCES[id].checked === 'text');

const contour = `
  <svg class="contour-field" viewBox="0 0 1100 420" preserveAspectRatio="none" aria-hidden="true">
    <path d="M-20,90 C 180,50 320,130 500,90 C 680,50 820,120 1120,80" fill="none" stroke-opacity="0.08" stroke-width="1"/>
    <path d="M-20,200 C 220,160 340,230 540,190 C 720,155 880,220 1120,185" fill="none" stroke-opacity="0.22" stroke-width="1"/>
    <path d="M-20,310 C 240,275 360,340 560,300 C 740,265 900,325 1120,290" fill="none" stroke-opacity="0.06" stroke-width="1"/>
  </svg>`;

function page({ path, depth, title, description, body }) {
  return `<!DOCTYPE html>
<!-- Generated by scripts/build-riding.mjs from content/riding/. Don't edit
     this file: change those and run  node scripts/build-riding.mjs
     DRAFT for coach review: kept out of search engines and not linked
     from the rest of the site. -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<base href="${'../'.repeat(depth)}">
<meta name="robots" content="noindex, nofollow">
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Big+Shoulders+Display:wght@700;800;900&family=Public+Sans:wght@400;500;600;700&family=JetBrains+Mono:wght@400;500;600&family=Newsreader:ital,opsz,wght@0,6..72,400;0,6..72,500;1,6..72,400&display=swap" rel="stylesheet">
<link rel="stylesheet" href="css/site.css?v=13">
<link rel="stylesheet" href="css/lab.css?v=6">
</head>
<body class="lab lab--riding">
<a class="skip-link" href="${path}#main">Skip to content</a>

<p class="ride-banner" role="note"><strong>Draft for coach review.</strong> Not published or approved. Nothing here is riding instruction yet.</p>

<nav class="site-nav" aria-label="Main">
  <div class="wrap">
    <a href="index.html" class="brand">Mathlete<span>.</span>MTB</a>
    <ul class="nav-links">
      <li><a href="index.html">The Lab</a></li>
      <li><a href="classes/">Classes</a></li>
      <li><a href="ski/">Ski</a></li>
      <li><a href="tutoring.html"><span class="nav-long">Private </span>Tutoring</a></li>
      <li><a href="about.html">About</a></li>
    </ul>
    <a class="nav-book" href="book.html">Book a Session</a>
  </div>
</nav>

<main id="main">
${body}
</main>

<footer class="footer">
  <div class="wrap">
    <span>&copy; 2026 Mathlete MTB LLC. All rights reserved.</span>
    <span class="footer-links"><a href="riding/">Riding curriculum (draft)</a></span>
  </div>
</footer>
</body>
</html>
`;
}

const pill = (text, cls = '') => `<li class="pill${cls ? ' ' + cls : ''}">${esc(text)}</li>`;
const statusPill = l => pill(STATUS[l.status], 'ride-status ride-status--' + l.status);
const isFull = l => l.status !== 'outline';
const riskPill = l => pill('Class ' + l.risk, 'ride-risk ride-risk--' + l.risk);

function sourceItem(id, note) {
  const s = SOURCES[id];
  return `<li class="ride-source">
          <a href="${esc(s.url)}" target="_blank" rel="noopener">${esc(s.title)}</a>
          <span class="meta">${esc(s.creator)} &middot; ${esc(ACCESS_LABELS[s.access])} &middot; <span class="ride-check ride-check--${s.checked}">${esc(CHECKED_LABELS[s.checked])}</span> &middot; ${id}</span>${note ? `\n          <span class="ride-source-note">${esc(note)}</span>` : ''}
        </li>`;
}

function section(id, label, inner) {
  return `
<section class="section ride-section" id="${id}" aria-labelledby="${id}-title">
  <div class="wrap split">
    <h2 class="label split-label" id="${id}-title">${label}</h2>
    <div class="prose ride-body">${inner}
    </div>
  </div>
</section>`;
}

const list = items => `\n      <ul class="ride-list">${items.map(i => `\n        <li>${esc(i)}</li>`).join('')}\n      </ul>`;

function reviewerBox(l) {
  const unchecked = allSources(l).filter(id => SOURCES[id].checked !== 'text');
  return `
<section class="section ride-review-wrap" aria-labelledby="review-title">
  <div class="wrap">
    <div class="ride-review">
      <h2 class="ride-review-title" id="review-title">For the reviewer</h2>
      <dl class="ride-facts">
        <div><dt>Reviewer needed</dt><dd>${esc(l.reviewer)}</dd></div>
        <div><dt>Status</dt><dd>${esc(STATUS[l.status])}</dd></div>
        <div><dt>Risk</dt><dd>${esc(RISK_CLASSES[l.risk].name)}${l.riskNote ? `<br><span class="meta">${esc(l.riskNote)}</span>` : ''}</dd></div>
        <div><dt>Text-verified source</dt><dd>${textVerified(l) ? 'Yes' : '<strong>No</strong>: the reviewer must supply or confirm the technical basis'}</dd></div>
      </dl>
      <p class="ride-review-sub">The reviewer must supply or confirm:</p>${list(l.specialist)}${unchecked.length ? `
      <p class="ride-review-sub">Watch or read before signing off (not yet checked):</p>${list(unchecked.map(id => `${id}: ${SOURCES[id].title} (${CHECKED_LABELS[SOURCES[id].checked]})`))}` : ''}
    </div>
  </div>
</section>`;
}

function lessonBody(l) {
  const pw = PATHWAYS.find(p => p.id === l.pathway);
  const head = `
<header class="page-head lab-head">${contour}
  <div class="wrap">
    <a class="lab-crumb" href="riding/#${pw.id}"><span aria-hidden="true">&larr;</span> Riding curriculum</a>
    <p class="eyebrow">${esc(pw.name)} &middot; ${esc(l.id)}</p>
    <h1 class="page-title ride-title">${esc(l.title)}</h1>
    <ul class="pill-row" aria-label="Lesson status">${statusPill(l)}${riskPill(l)}${pill('Release ' + l.release)}</ul>
  </div>
</header>
${reviewerBox(l)}`;

  const sourcesSection = section('sources', 'Further learning', `
      <p>Original Mathlete writing. These sources are linked for further learning; none of them has endorsed Mathlete.</p>
      <ul class="ride-sources">
        ${[...l.sources.primary, ...l.sources.comparison].map(id => sourceItem(id, (l.examples || []).find(e => e.id === id)?.note)).join('\n        ')}
      </ul>`);
  const safety = section('safety', 'Safety', `
      <p><strong>${esc(RISK_CLASSES[l.risk].name)}.</strong> ${esc(RISK_CLASSES[l.risk].text)}</p>
      <p>Practice only on terrain your coach has chosen, within your current skill, with the right protective equipment. Completing a lesson isn’t a safety certificate and doesn’t mean a rider is ready to try anything.</p>`);

  if (l.status === 'outline') {
    return head + section('outcome', 'Lesson goal', `
      <p>${esc(l.outcome)}</p>`) + section('coverage', 'What it will cover', list(l.coverage)) +
      (l.physicsIdea ? section('physics', 'Physics &amp; maths', `
      <p>${esc(l.physicsIdea)}</p>`) : '') + safety + sourcesSection;
  }

  const unchecked = l.sources.primary.filter(id => SOURCES[id].checked !== 'text');
  return head +
    section('outcome', 'Performance outcome', `
      <p>${esc(l.outcome)}</p>`) +
    section('who', 'Who it’s for', `
      <p>${esc(l.who)}</p>
      <p class="ride-sub">Before this lesson</p>${list(l.prereqs)}`) +
    section('why', 'Why it matters', `
      <p>${esc(l.why)}</p>`) +
    section('model', 'Technical model', `${unchecked.length ? `
      <p class="ride-flag">Source check: ${unchecked.map(id => `${id} (${esc(CHECKED_LABELS[SOURCES[id].checked].toLowerCase())})`).join(', ')}. The reviewer must confirm this section against the original.</p>` : ''}
      ${l.model.map(m => `<h3 class="ride-h">${esc(m.h)}</h3>
      <p>${esc(m.p)}</p>`).join('\n      ')}`) +
    (l.physics ? section('physics', 'Physics &amp; maths', `
      <h3 class="ride-h">${esc(l.physics.h)}</h3>
      <p>${esc(l.physics.p)}</p>
      <p class="meta">${esc(l.physics.note)}</p>`) : '') +
    section('errors', 'Common errors', `
      <div class="ride-table-wrap"><table class="ride-table">
        <thead><tr><th scope="col">What you see</th><th scope="col">Possible causes</th><th scope="col">Correction</th></tr></thead>
        <tbody>${l.errors.map(e => `
          <tr><td>${esc(e.pattern)}</td><td>${esc(e.causes)}</td><td class="ride-pending">Coach to supply</td></tr>`).join('')}
        </tbody>
      </table></div>`) +
    (l.disagreements ? section('disagreements', 'Where sources disagree', list(l.disagreements)) : '') +
    section('practice', 'Practice design', `
      <dl class="ride-facts ride-facts--stack">
        <div><dt>Setting</dt><dd>${esc(l.practice.setting)}</dd></div>
        <div><dt>Focus</dt><dd>${esc(l.practice.focus)}</dd></div>
        <div><dt>Feedback</dt><dd>${esc(l.practice.feedback)}</dd></div>
      </dl>
      <p class="ride-sub">Stop when</p>${list(l.practice.stop)}`) +
    section('rubric', 'Video analysis', `
      <p>What the rider and coach look for in footage:</p>${list(l.rubric)}`) +
    section('gates', 'Ready to move on', `${list(l.gates)}
      <p class="meta">Educational checkpoints, not safety certificates.</p>`) +
    (l.next.length ? section('next', 'Next', `
      <ul class="lab-also">
        ${l.next.map(s => `<li><a href="riding/${s}/">${esc(bySlug[s].title)}</a></li>`).join('\n        ')}
      </ul>`) : '') +
    safety + sourcesSection;
}

function indexBody() {
  const counts = s => LESSONS.filter(l => l.status === s).length;
  const pathways = PATHWAYS.map(p => {
    const mine = LESSONS.filter(l => l.pathway === p.id);
    return `
<section class="section ride-pathway" id="${p.id}" aria-labelledby="${p.id}-title">
  <div class="wrap">
    <div class="lab-section-head">
      <h2 class="label" id="${p.id}-title">${esc(p.name)}</h2>
    </div>
    <p class="ride-intro">${esc(p.intro)}</p>
    <div class="tool-grid">${mine.map(l => `
      <a class="tool-card ride-card ride-card--${l.status}" href="riding/${l.slug}/">
        <div class="tool-card-body">
          <p class="kicker">${esc(l.id)}</p>
          <h3 class="tool-card-title">${esc(l.title)}</h3>
          <ul class="pill-row">${statusPill(l)}${riskPill(l)}</ul>
          <p class="tool-card-desc">${esc(l.reviewer)}</p>
        </div>
      </a>`).join('')}
    </div>
  </div>
</section>`;
  }).join('');

  const rows = LESSONS.map(l => `
          <tr><td>${esc(l.id)}</td><td><a href="riding/${l.slug}/">${esc(l.title)}</a></td><td>${l.risk}</td><td>${l.release}</td><td>${textVerified(l) ? 'Yes' : '<strong>No</strong>'}</td><td>${esc(l.reviewer)}</td><td>${esc(STATUS[l.status])}</td></tr>`).join('');
  const used = id => LESSONS.filter(l => allSources(l).includes(id)).length;
  const srcRows = Object.entries(SOURCES).map(([id, s]) => `
          <tr><td>${id}</td><td><a href="${esc(s.url)}" target="_blank" rel="noopener">${esc(s.title)}</a><br><span class="meta">${esc(s.creator)}</span></td><td>${esc(ACCESS_LABELS[s.access])}</td><td><span class="ride-check ride-check--${s.checked}">${esc(CHECKED_LABELS[s.checked])}</span></td><td>${used(id)}</td></tr>`).join('');

  return `
<header class="page-head lab-head">${contour}
  <div class="wrap">
    <p class="eyebrow">Riding Lab &middot; Draft for coach review</p>
    <h1 class="page-title">Advanced Performance Curriculum</h1>
    <p class="hero-lede">Mathlete’s riding curriculum for advanced riders, racers and freestyle athletes. Every lesson here is a draft waiting for review by a qualified coach. ${LESSONS.filter(isFull).length} are written in full, and ${counts('outline')} are outlines that still need an author.</p>
    <ul class="pill-row" aria-label="Status">${pill(counts('draft') + ' ready for review', 'ride-status ride-status--draft')}${pill(counts('specialist') + ' need a specialist', 'ride-status ride-status--specialist')}${pill(counts('outline') + ' outlines', 'ride-status ride-status--outline')}${pill(counts('approved') + ' approved', 'ride-status ride-status--approved')}</ul>
  </div>
</header>

<section class="section" aria-labelledby="classes-title">
  <div class="wrap split">
    <h2 class="label split-label" id="classes-title">Risk classes</h2>
    <dl class="ride-facts ride-facts--stack">${Object.values(RISK_CLASSES).map(r => `
      <div><dt>${esc(r.name)}</dt><dd>${esc(r.text)}</dd></div>`).join('')}
    </dl>
  </div>
</section>
${pathways}
<section class="section section--panel" id="coverage" aria-labelledby="coverage-title">
  <div class="wrap">
    <div class="lab-section-head"><h2 class="label" id="coverage-title">Coverage</h2></div>
    <div class="ride-table-wrap"><table class="ride-table">
      <thead><tr><th scope="col">Brief</th><th scope="col">Lesson</th><th scope="col">Class</th><th scope="col">Release</th><th scope="col">Text-verified source</th><th scope="col">Reviewer</th><th scope="col">Status</th></tr></thead>
      <tbody>${rows}
      </tbody>
    </table></div>
  </div>
</section>

<section class="section" id="sources" aria-labelledby="sources-title">
  <div class="wrap">
    <div class="lab-section-head"><h2 class="label" id="sources-title">Sources</h2></div>
    <p class="ride-intro">Linked as further learning only. None of these creators or organisations has endorsed Mathlete. Lessons use original Mathlete writing; most sources could not be read automatically, so reviewers should check the originals.</p>
    <div class="ride-table-wrap"><table class="ride-table">
      <thead><tr><th scope="col">ID</th><th scope="col">Source</th><th scope="col">Access</th><th scope="col">Checked</th><th scope="col">Lessons</th></tr></thead>
      <tbody>${srcRows}
      </tbody>
    </table></div>
  </div>
</section>
`;
}

export function render() {
  const pages = {
    'riding/index.html': page({
      path: 'riding/', depth: 1,
      title: 'Riding Curriculum (Draft) — Mathlete MTB',
      description: 'Draft advanced riding curriculum awaiting coach review.',
      body: indexBody()
    })
  };
  for (const l of LESSONS) {
    pages[`riding/${l.slug}/index.html`] = page({
      path: `riding/${l.slug}/`, depth: 2,
      title: `${l.title} (Draft) — Mathlete MTB`,
      description: `Draft lesson awaiting coach review: ${l.outcome}`,
      body: lessonBody(l)
    });
  }
  return pages;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const [p, html] of Object.entries(render())) {
    mkdirSync(root + p.replace(/[^/]+$/, ''), { recursive: true });
    writeFileSync(root + p, html);
  }
  console.log(`wrote riding/ (${LESSONS.length} lessons)`);
}

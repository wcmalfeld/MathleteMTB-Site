//   resources/view/index.html     one resource (?r=<slug>)
//   resources/manage/index.html   add, edit, publish (admins, tutors, schools)
// The resources themselves live in Supabase (supabase/library.sql) and are
// loaded in the browser (js/library.js, js/library-manage.js), because who
// may see each one depends on who is signed in. These shells only hold the
// layout. Run  node scripts/build-resources.mjs  after changing this file.


// ---------- supabase/curriculum.sql ----------
const q = s => `'${String(s).replace(/'/g, "''")}'`;
function curriculumSql(model) {
  const skills = model.skills.map(s => `  (${q(s.id)}, ${q(s.topic.course.id)}, ${q(s.topic.id)}, ${q(s.title)})`).join(',\n');
  const tracked = model.activities.filter(a => a.tracking);
  const kinds = tracked.flatMap(a => Object.entries(a.tracking.questions).map(([qid, ss]) => ({ id: `${a.tracking.gameId}:${qid.toLowerCase()}`, game: a.tracking.gameId, title: `${a.title}: question ${qid}`, ss })));
  return `-- ============================================================
-- GENERATED by scripts/build-classes.mjs from content/classes/.
-- Don't edit: change the content and run  node scripts/build-classes.mjs
-- Then paste this whole file into Supabase -> SQL Editor and Run (after
-- setup.sql and progress.sql). Safe to re-run.
--
-- What it adds:
--   * curriculum_skills           every skill in Classes, by its stable id
--   * curriculum_question_skills  which activity questions practise which
--                                 curriculum skills (an attempt at one
--                                 question counts for all its skills)
--   * question kinds for tracked activities (e.g. the Slope Lab), so
--     record_attempt() accepts them
--   * curriculum_progress()       a student's progress per curriculum skill
--                                 and per tracked activity
-- Who can see what: the same rules as the rest of progress.sql (a student
-- sees their own; a tutor sees assigned students; an admin sees all).
-- ============================================================

create table if not exists public.curriculum_skills (
  id         text primary key check (id ~ '^[a-z0-9]+(\\.[a-z0-9-]+)+$'),
  course_id  text not null,
  topic_id   text not null,
  title      text not null,
  active     boolean not null default true
);
create table if not exists public.curriculum_question_skills (
  question_id text not null references public.questions (id) on delete cascade,
  skill_id    text not null references public.curriculum_skills (id) on delete cascade,
  primary key (question_id, skill_id)
);
create index if not exists curriculum_question_skills_skill_idx on public.curriculum_question_skills (skill_id);

alter table public.curriculum_skills enable row level security;
alter table public.curriculum_question_skills enable row level security;
drop policy if exists "Members read curriculum skills" on public.curriculum_skills;
create policy "Members read curriculum skills" on public.curriculum_skills for select to authenticated using ((select public.has_tool_access()));
drop policy if exists "Members read curriculum links" on public.curriculum_question_skills;
create policy "Members read curriculum links" on public.curriculum_question_skills for select to authenticated using ((select public.has_tool_access()));
revoke all on public.curriculum_skills, public.curriculum_question_skills from anon, authenticated;
grant select on public.curriculum_skills, public.curriculum_question_skills to authenticated;

-- 1. Skills (ids are permanent; a skill removed from the content is
--    marked inactive, never deleted, so old progress keeps its meaning).
update public.curriculum_skills set active = false;
insert into public.curriculum_skills (id, course_id, topic_id, title) values
${skills}
on conflict (id) do update set course_id = excluded.course_id, topic_id = excluded.topic_id, title = excluded.title, active = true;

-- 2. Question kinds for tracked activities, filed under the broad
--    'algebra' skill for the dashboard's skill meters.
insert into public.questions (id, game_id, title, difficulty) values
${kinds.map(k => `  (${q(k.id)}, ${q(k.game)}, ${q(k.title)}, null)`).join(',\n')}
on conflict (id) do update set game_id = excluded.game_id, title = excluded.title, active = true;
insert into public.question_skills (question_id, skill_id) values
${kinds.map(k => `  (${q(k.id)}, 'algebra')`).join(',\n')}
on conflict do nothing;

-- 3. Which curriculum skills each question practises.
delete from public.curriculum_question_skills where question_id in (${[...new Set(kinds.map(k => k.game))].map(g => `select id from public.questions where game_id = ${q(g)}`).join(' union ')});
insert into public.curriculum_question_skills (question_id, skill_id) values
${kinds.flatMap(k => k.ss.map(s => `  (${q(k.id)}, ${q(s)})`)).join(',\n')}
on conflict do nothing;

-- 4. Progress per curriculum skill (only skills with activity are listed)
--    and per tracked activity, for the signed-in student or one a tutor
--    is assigned. p_prefix narrows it, e.g. 'alg1.' for one course.
create or replace function public.curriculum_progress(p_prefix text default null, p_student uuid default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_sid uuid := coalesce(p_student, auth.uid());
begin
  if auth.uid() is null or not public.has_tool_access() then
    raise sqlstate 'PT403' using message = 'Sign in with an active account.';
  end if;
  if v_sid <> auth.uid() and v_sid not in (select public.my_student_ids()) then
    raise sqlstate 'PT403' using message = 'That student is not assigned to you.';
  end if;
  return jsonb_build_object(
    'skills', coalesce((
      select jsonb_object_agg(x.skill_id, jsonb_build_object('questions', x.n, 'first_try', x.ok, 'last_at', x.last_at))
      from (
        select cqs.skill_id, count(*) n, count(*) filter (where f.first_correct) ok, max(f.occurred_at) last_at
        from public.question_first_tries f
        join public.curriculum_question_skills cqs on cqs.question_id = f.question_id
        where f.student_id = v_sid and (p_prefix is null or cqs.skill_id like p_prefix || '%')
        group by cqs.skill_id
      ) x), '{}'::jsonb),
    'activities', coalesce((
      select jsonb_object_agg(s.game_id, jsonb_build_object('sessions', s.n, 'completed', s.done, 'last_at', s.last_at))
      from (
        select g.game_id, count(*) n, count(*) filter (where g.completed) done, max(coalesce(g.ended_at, g.started_at)) last_at
        from public.game_sessions g
        where g.student_id = v_sid and g.game_id in (select distinct q.game_id from public.questions q
                                                     join public.curriculum_question_skills c on c.question_id = q.id)
        group by g.game_id
      ) s), '{}'::jsonb));
end;
$$;
revoke all on function public.curriculum_progress(text, uuid) from public, anon;
grant execute on function public.curriculum_progress(text, uuid) to authenticated;
`;
}

export function render() {
  const model = loadClasses();
  if (model.errors.length) throw new Error('content/classes has problems:\n  ' + model.errors.join('\n  '));
  const pages = { 'classes/index.html': landing(model) };
  for (const c of model.courses) {
    pages[c.href + 'index.html'] = coursePage(c, model);
    for (const u of c.units) for (const t of u.topics) pages[t.href + 'index.html'] = topicPage(t, model);
  }
  pages['supabase/curriculum.sql'] = curriculumSql(model);
  return pages;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const pages = render();
  // Remove topic folders that no longer exist in the content.
  const want = new Set(Object.keys(pages));
  if (existsSync(root + 'classes')) for (const course of readdirSync(root + 'classes')) {
    const cdir = root + 'classes/' + course;
    if (!statSync(cdir).isDirectory()) continue;
    for (const topic of readdirSync(cdir)) {
      const f = `classes/${course}/${topic}/index.html`;
      if (statSync(cdir + '/' + topic).isDirectory() && !want.has(f)) { rmSync(cdir + '/' + topic, { recursive: true }); console.log('removed ' + f); }
    }
    if (!want.has(`classes/${course}/index.html`)) { rmSync(cdir, { recursive: true }); console.log('removed classes/' + course); }
  }
  let n = 0;
  for (const [p, html] of Object.entries(pages)) {
    mkdirSync(root + p.replace(/[^/]+$/, ''), { recursive: true });
    writeFileSync(root + p, html); n++;
  }
  console.log(`wrote ${n} files (classes/ and supabase/curriculum.sql)`);
}
